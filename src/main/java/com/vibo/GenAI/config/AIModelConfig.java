package com.vibo.GenAI.config;

import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.chat.client.advisor.MessageChatMemoryAdvisor;
import org.springframework.ai.chat.memory.ChatMemory;
import org.springframework.ai.chat.memory.MessageWindowChatMemory;
import org.springframework.ai.chat.model.ChatModel;
import org.springframework.ai.embedding.EmbeddingModel;
import org.springframework.ai.image.ImageGeneration;
import org.springframework.ai.image.ImageModel;
import org.springframework.ai.image.ImagePrompt;
import org.springframework.ai.image.ImageResponse;
import org.springframework.ai.vectorstore.VectorStore;
import org.springframework.ai.vectorstore.pgvector.PgVectorStore;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;

import java.util.Base64;
import java.util.List;

@Configuration
public class AIModelConfig {

    private final ChatModel chatModel;

    public AIModelConfig(@Qualifier("googleGenAiChatModel") ChatModel chatModel) {
        this.chatModel = chatModel;
    }

    @Bean
    public ChatClient chatClient() {
        ChatMemory chatMemory = MessageWindowChatMemory.builder()
                .maxMessages(20)
                .build();

        return ChatClient.builder(chatModel)
                .defaultAdvisors(
                        MessageChatMemoryAdvisor.builder(chatMemory)
                                .build()
                )
                .build();
    }

    @Bean
    public VectorStore vectorStore(
            JdbcTemplate jdbcTemplate,
            @Qualifier("googleGenAiTextEmbedding") EmbeddingModel embeddingModel) {

        return PgVectorStore.builder(jdbcTemplate, embeddingModel)
                .dimensions(768)
                .build();
    }

    @Bean
    public ImageModel imageModel(com.google.genai.Client client) {
        return (ImagePrompt prompt) -> {
            String message = prompt.getInstructions().get(0).getText();
            com.google.genai.types.GenerateImagesResponse response = client.models.generateImages(
                    "imagen-3.0-generate-002",
                    message,
                    com.google.genai.types.GenerateImagesConfig.builder()
                            .numberOfImages(1)
                            .outputMimeType("image/jpeg")
                            .build()
            );
            if (response.generatedImages().isPresent() && !response.generatedImages().get().isEmpty()) {
                byte[] bytes = response.generatedImages().get().get(0).image().get().imageBytes().get();
                String b64 = Base64.getEncoder().encodeToString(bytes);
                return new ImageResponse(List.of(new ImageGeneration(new org.springframework.ai.image.Image(null, "data:image/jpeg;base64," + b64))));
            }
            throw new RuntimeException("No image generated by Gemini Imagen model");
        };
    }
}
